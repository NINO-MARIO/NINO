const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = path.resolve(__dirname, '..', '..');
let pass = 0, fail = 0;
function ok(c, n) { if (c) pass++; else { fail++; console.log('  FAIL: ' + n); } }
const store = {};
const sandbox = { window: {}, localStorage: { getItem: k => (k in store ? store[k] : null), setItem: (k, v) => { store[k] = String(v); } }, CustomEvent: function () {}, Map: Map };
sandbox.window.dispatchEvent = () => {};
sandbox.window.addEventListener = () => {};
vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'js/mood.js'), 'utf8'), sandbox);
vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'js/cg-pick.js'), 'utf8'), sandbox);
const P = sandbox.window.ninoCgPick.pure;
console.log('== CG picker: prompt block and tag parsing');
const counts = { HAPPY: 1, SAD: 0, SASSY: 0, THINKING: 0, ANGRY: 0, NEUTRAL: 2 };
const block = P.block(counts);
ok(block.indexOf('HAPPY') >= 0 && block.indexOf('NEUTRAL') >= 0, 'block lists categories that have items');
ok(block.indexOf('SAD') < 0, 'block does not list empty categories');
ok(block.indexOf('[[CG:NONE]]') >= 0, 'block tells the model how to answer with NONE');
ok(P.block({ HAPPY: 0, SAD: 0, SASSY: 0, THINKING: 0, ANGRY: 0, NEUTRAL: 0 }) === '', 'no items means no block');
ok(!/\.(jpg|png|mp4|webp)|blob|url/i.test(block), 'block carries no file names or URLs');
const t1 = P.take('ดีใจมากเลย 555\n[[CG:HAPPY]]', counts, true);
ok(t1.text === 'ดีใจมากเลย 555' && t1.cg === 'HAPPY', 'tag is removed and the pick is kept');
const t2 = P.take('เศร้าจัง [[CG:SAD]]', counts, true);
ok(t2.cg === 'NONE', 'a category without items falls back to NONE');
const t3 = P.take('ข้อความธรรมดา', counts, true);
ok(t3.cg === 'NONE' && t3.text === 'ข้อความธรรมดา', 'no tag means NONE and text unchanged');
const t4 = P.take('ตอบ [[CG:happy]]', counts, true);
ok(t4.cg === 'HAPPY', 'tag is case-insensitive');
const t5 = P.take('ตอบ [[CG:HAPPY]] แล้วก็ [[CG:NEUTRAL]]', counts, true);
ok(t5.cg === 'NEUTRAL' && t5.text.indexOf('[[') < 0, 'last tag wins and every tag is removed');
const t6 = P.take('ดีใจ [[CG:HAPPY]]', counts, false);
ok(t6.cg === '' && t6.text === 'ดีใจ', 'when OFF the tag is removed and no pick is kept');
ok(P.strip('กำลังพิมพ์ [[CG:HA') === 'กำลังพิมพ์', 'partial tag at the end of a stream is hidden');
ok(P.strip('ข้อความ [[ปกติ]]') === 'ข้อความ [[ปกติ]]', 'unrelated double brackets are kept');
ok(P.take('', counts, true).cg === 'NONE', 'empty text is NONE');
console.log('passed ' + pass + ', failed ' + fail);
process.exit(fail ? 1 : 0);
