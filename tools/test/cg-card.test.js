const H = require('./harness.js'), path = require('path');
const ROOT = H.ROOT;
let pass = 0, fail = 0;
function ok(c, n) { if (c) pass++; else { fail++; console.log('  FAIL: ' + n); } }
const sleep = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  console.log('== CG library and AI-picked chat card (browser)');
  const h = await H.start();
  const P = h.page;
  await P.goto(h.base + '/index.html', { waitUntil: 'load' });
  await sleep(2000);
  ok(await P.evaluate(() => typeof window.ninoCg === 'object' && typeof window.ninoCgPick === 'object' && typeof window.ninoChatCard === 'object'), 'modules loaded');
  ok(await P.evaluate(() => !!document.getElementById('nd-cg')), 'CG button in drawer');
  await P.click('#app-header .w-7.h-7');
  await sleep(400);
  await P.click('#nd-cg');
  await sleep(600);
  ok(await P.evaluate(() => document.getElementById('nino-cg').classList.contains('on')), 'CG sheet opens from drawer');
  ok(await P.evaluate(() => document.getElementById('ncg-on').checked === false), 'AI visibility switch starts OFF');
  await P.click('.ncg-tab[data-cat="HAPPY"]');
  await P.setInputFiles('#ncg-file', [path.join(ROOT, 'assets/classroom/nino-read.webp')]);
  await sleep(900);
  ok(await P.evaluate(() => document.querySelectorAll('#ncg-grid .ncg-card').length) === 1, 'image added to HAPPY');
  ok(await P.evaluate(() => /บันทึกสำเร็จ 1 ไฟล์/.test(document.getElementById('ncg-status').textContent)), 'status line confirms the save');
  await P.click('.ncg-tab[data-cat="SAD"]');
  await P.setInputFiles('#ncg-file', [path.join(ROOT, 'assets/classroom/nino-read.mp4')]);
  await sleep(1200);
  ok(await P.evaluate(() => document.querySelectorAll('#ncg-grid .ncg-card video').length) === 1, 'video added to SAD');
  await P.click('.ncg-tab[data-cat="SAD"]');
  await sleep(200);
  await P.evaluate(() => { window.__big = new File([new Uint8Array(45 * 1024 * 1024)], 'phone-clip.mp4', { type: '' }); });
  await P.evaluate(async () => { const dt = new DataTransfer(); dt.items.add(window.__big); const inp = document.getElementById('ncg-file'); inp.files = dt.files; inp.dispatchEvent(new Event('change')); });
  await sleep(2500);
  const bigStatus = await P.evaluate(() => document.getElementById('ncg-status').textContent);
  ok(/บันทึกสำเร็จ 1 ไฟล์/.test(bigStatus), 'a 45 MB video with no MIME type is accepted: ' + bigStatus.slice(0, 80));
  ok(await P.evaluate(() => document.querySelectorAll('#ncg-grid .ncg-card').length) === 2, 'SAD now has two items');
  await P.click('.ncg-x');
  await sleep(300);
  await P.evaluate(() => {
    session.messages.push({ sender: 'nino', action: 'explain', reply: 'ขอโทษนะคะ ฉันเสียใจที่รู้สึกแบบนี้', streaming: false, ts: Date.now(), turn: 1, cg: 'SAD' });
    session.messages.push({ sender: 'nino', action: 'explain', reply: 'ดีใจมากเลย', streaming: false, ts: Date.now(), turn: 2, cg: 'HAPPY' });
    session.messages.push({ sender: 'nino', action: 'explain', reply: 'ตอนนี้เวลาสิบโมง', streaming: false, ts: Date.now(), turn: 3, cg: 'NONE' });
    session.messages.push({ sender: 'nino', action: 'explain', reply: 'กำลังพิมพ์อยู่', streaming: true, ts: Date.now(), turn: 4 });
    renderMessages();
  });
  await sleep(500);
  ok(await P.evaluate(() => document.querySelectorAll('.nino-cc').length) === 0, 'switch OFF: no card even when messages carry picks');
  await P.evaluate(() => window.ninoCgPick.setOn(true));
  await sleep(500);
  const badges = await P.evaluate(() => [...document.querySelectorAll('.nino-cc .nino-cc-badge')].map(b => b.textContent));
  ok(badges.length === 2, 'switch ON: cards only for the two picked messages, got ' + JSON.stringify(badges));
  ok(badges[0] && badges[0].indexOf('AI เลือก: SAD') === 0, 'SAD pick shows the AI choice label');
  ok(badges[1] && badges[1].indexOf('AI เลือก: HAPPY') === 0, 'HAPPY pick shows the AI choice label');
  const sad = await P.evaluate(() => { const v = document.querySelector('.nino-cc [data-cc-slot="SAD"] video'); if (v) v.__mark = 'keep'; return !!v; });
  ok(sad, 'SAD slot shows the video');
  ok(await P.evaluate(() => !!document.querySelector('.nino-cc [data-cc-slot="HAPPY"] img')), 'HAPPY slot shows the image');
  await P.evaluate(() => { renderMessages(); renderMessages(); });
  await sleep(500);
  ok(await P.evaluate(() => { const v = document.querySelector('.nino-cc [data-cc-slot="SAD"] video'); return !!(v && v.__mark === 'keep'); }), 'same video element is reused after re-renders (no reload)');
  ok(await P.evaluate(() => /^\d+%$/.test(document.querySelector('.nino-cc-num').textContent)), 'energy bar label is a percentage');
  await P.reload({ waitUntil: 'load' });
  await sleep(2000);
  await P.click('#app-header .w-7.h-7');
  await sleep(400);
  await P.click('#nd-cg');
  await sleep(500);
  await P.click('.ncg-tab[data-cat="SAD"]');
  await sleep(400);
  ok(await P.evaluate(() => document.querySelectorAll('#ncg-grid .ncg-card').length) === 2, 'uploads survive a page reload');
  await P.evaluate(() => { window.confirm = () => true; });
  await (await P.$('#ncg-grid .ncg-del')).click();
  await sleep(900);
  ok(await P.evaluate(() => document.querySelectorAll('#ncg-grid .ncg-card').length) === 1, 'delete removes one item');
  ok(h.errors.length === 0, 'no page errors: ' + JSON.stringify(h.errors.slice(0, 3)));
  await h.close();
  console.log('passed ' + pass + ', failed ' + fail);
  process.exit(fail ? 1 : 0);
})().catch(e => { console.error('CRASH', e); process.exit(2); });
