/* มิ้ม | 45-manners
 * คลาสมารยาท: ปรับประโยคให้สุภาพแบบผู้หญิง (ลงท้ายค่ะ/คะ) ก่อนเข้าคลังความรู้
 *
 * ใช้กับข้อความที่ระบบสร้างเองในกระบวนการสร้าง .txt อัตโนมัติ (ดู 46-textpipe.js)
 * ไม่ใช้กับความรู้ที่ผู้ใช้สอนเอง เพราะคำตอบของผู้ใช้เป็นข้อมูลของเขา ระบบไม่ควรแก้ไขเอง
 *
 * กฎ:
 *   - ถ้าลงท้ายด้วยคำลงท้ายสุภาพอยู่แล้ว (ค่ะ คะ ครับ นะ จ้า) ไม่แก้
 *   - คำถามที่ลงท้ายด้วย "ไหม" หรือ "มั้ย" ได้ "ไหมคะ"
 *   - คำถามอื่น (อะไร ยังไง ทำไม ฯลฯ) ได้ "คะ" ต่อท้าย
 *   - ประโยคบอกเล่าทั่วไปได้ "ค่ะ"
 *   - ตัดเครื่องหมายวรรคตอนท้ายประโยคก่อน ไม่เพิ่มอิโมจิเด็ดขาด
 */
(function (root) {
  'use strict';
  const NINO = root.NINO;

  const POLITE_END = /(ค่ะ|คะ|นะคะ|นะค่ะ|ครับ|นะครับ|จ้า|จ้ะ)$/;
  const ASK_YES_NO = /(ไหม|มั้ย)$/;
  const ASK_WH = /(อะไร|ที่ไหน|เมื่อไร|เมื่อไหร่|ใคร|ทำไม|ยังไง|อย่างไร|เท่าไร|เท่าไหร่|หรือเปล่า|บ้าง)$/;

  const Manners = {
    polish(text) {
      const t = String(text ?? '').replace(/\s+/g, ' ').trim().replace(/[.!?…]+$/, '').trim();
      if (!t) return '';
      if (POLITE_END.test(t)) return t;
      if (ASK_YES_NO.test(t)) return t + 'คะ';
      if (ASK_WH.test(t)) return t + 'คะ';
      return t + 'ค่ะ';
    }
  };

  NINO.Manners = Manners;
})(typeof globalThis !== 'undefined' ? globalThis : this);
