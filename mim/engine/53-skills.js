/* มิ้ม | 53-skills
 * ทักษะกฎตายตัวที่คำนวณหรืออ่านจากข้อความได้จริง (ไม่ใช่การเดา) ทำก่อนการค้นความรู้
 *   - เลขคณิต: "2 บวก 3 เท่ากับเท่าไร" (บวก ลบ คูณ หาร และสัญลักษณ์)
 *   - วันที่สัมพันธ์: พรุ่งนี้ มะรืน เมื่อวาน วันอะไร
 *   - คำตรงข้ามจากตารางเล็กที่เขียนไว้
 *   - ตอบความรู้สึก (เครียด เศร้า) และคำชม/คำด่าแบบสุภาพ
 *   - ข้อความที่แสดงว่าอาจทำร้ายตัวเอง: ตอบด้วยช่องทางขอความช่วยเหลือก่อนเรื่องอื่นทั้งหมด
 *   - นิทานสั้นที่เขียนขึ้นใหม่ (ไม่ได้คัดลอกจากที่ใด)
 */
(function (root) {
  'use strict';
  const NINO = root.NINO;
  const Text = NINO.Text;

  const THAI_MONTHS = ['มกราคม', 'กุมภาพันธ์', 'มีนาคม', 'เมษายน', 'พฤษภาคม', 'มิถุนายน',
    'กรกฎาคม', 'สิงหาคม', 'กันยายน', 'ตุลาคม', 'พฤศจิกายน', 'ธันวาคม'];
  const THAI_DAYS = ['วันอาทิตย์', 'วันจันทร์', 'วันอังคาร', 'วันพุธ', 'วันพฤหัสบดี', 'วันศุกร์', 'วันเสาร์'];

  const CRISIS_RE = /(ฆ่าตัวตาย|อยากตาย|อยากจะตาย|ไม่อยากมีชีวิต|ไม่อยากอยู่แล้ว|อยากหายไปจากโลก|ทำร้ายตัวเอง)/;
  const CRISIS = 'ฟังแล้วเป็นห่วงมากเลยค่ะ ความรู้สึกแบบนี้หนักมาก ตอนนี้คุณปลอดภัยดีไหมคะ ' +
    'ถ้าคิดจะทำร้ายตัวเอง ลองโทรหาสายด่วนสุขภาพจิต 1323 (ทำงาน 24 ชั่วโมง) หรือ 1669 ถ้าเป็นเหตุฉุกเฉิน ' +
    'ตอนนี้มีใครอยู่ใกล้คุณไหมคะ ลองบอกเขาได้เลยนะคะ';

  const ANXIOUS_RE = /(เครียด|กดดัน|ไม่สบายใจ|กังวล|กลัว|วิตก|ตื่นเต้นมาก)/;
  const SAD_RE = /(เศร้า|เหงา|ท้อ(?!ง)|หดหู่|ทุกข์ใจ|เหนื่อยใจ|คิดถึงบ้าน|ร้องไห้)/;
  const ANXIOUS = [
    'เข้าใจเลยค่ะว่ามันกดดันแค่ไหน ลองเล่าให้ฟังได้นะคะว่าอะไรทำให้รู้สึกแบบนี้',
    'ลองหายใจลึกๆ สักสามครั้งก่อนนะคะ แล้วค่อยๆ บอกฉันว่าอะไรที่ทำให้กังวลที่สุดคะ',
    'ความกังวลแบบนี้ไม่ใช่เรื่องแปลกเลยค่ะ อยากให้ช่วยแยกเรื่องที่ทำได้กับที่ทำไม่ได้ไหมคะ'
  ];
  const SAD = [
    'ฟังแล้วเสียใจด้วยนะคะ อยากเล่าให้ฟังไหมคะว่าเกิดอะไรขึ้น',
    'ขอบคุณที่บอกนะคะ ตอนนี้ลองพักและดูแลตัวเองสักหน่อยดีไหมคะ',
    'เหนื่อยใจก็พักได้นะคะ ฉันอยู่ตรงนี้ถ้าอยากคุยต่อ'
  ];
  const INSULT_RE = /(โง่|ห่วย|ไร้ประโยชน์|ไม่เก่ง|ไม่ฉลาด|ควาย|งี่เง่า)/;
  const PRAISE_RE = /(น่ารัก|เก่งจัง|เก่งมาก|เก่งจริง|ฉลาดจัง|ฉลาดมาก|เยี่ยม)/;
  const INSULT = [
    'ขอโทษค่ะถ้าคำตอบยังไม่ดีพอ ลองบอกฉันได้ไหมคะว่าอยากให้ตอบเรื่องไหนให้ดีขึ้น',
    'รับฟังค่ะ มิ้มยังเรียนรู้อยู่ ถ้าสอนฉันได้ก็จะดีขึ้นค่ะ'
  ];
  const PRAISE = [
    'ขอบคุณนะคะ ดีใจที่ชอบค่ะ',
    'ขอบคุณที่ให้กำลังใจค่ะ มิ้มจะพยายามต่อไปนะคะ'
  ];
  const STORIES = [
    'มีกระต่ายตัวหนึ่งอยากข้ามลำธารไปหาเพื่อน แต่น้ำเชี่ยว มันจึงเก็บหินเรียงเป็นทางทีละก้อน ' +
      'จนถึงฝั่งได้ในที่สุด เพื่อนถามว่าเหนื่อยไหม มันตอบว่าทีละนิดก็ถึงได้เหมือนกันค่ะ',
    'ชาวนาคนหนึ่งปลูกข้าวได้น้อยกว่าปีก่อน เขาไม่ท้อ แต่ไปถามเพื่อนบ้านว่าดินเป็นอย่างไร ' +
      'พอปรับดินและเปลี่ยนวิธีปลูก ปีถัดมาข้าวก็งอกงามดี เขาสอนลูกว่าการเรียนรู้จากเรื่องเดิมคือกำไรอย่างหนึ่ง',
    'เด็กหญิงคนหนึ่งเขียนจดหมายถึงทะเลทุกคืน แล้วโยนลงน้ำ วันหนึ่งมีจดหมายตอบกลับมา ' +
      'เขียนว่า "ขอบคุณที่เล่าให้ฟังนะ ฉันชอบเสียงคลื่นของเธอ" เด็กหญิงยิ้มและเขียนต่อไปทุกคืน'
  ];
  const ANTONYMS = {
    'ร้อน': 'หนาว', 'หนาว': 'ร้อน', 'เร็ว': 'ช้า', 'ช้า': 'เร็ว', 'ใหญ่': 'เล็ก', 'เล็ก': 'ใหญ่',
    'สูง': 'ต่ำ', 'ต่ำ': 'สูง', 'สว่าง': 'มืด', 'มืด': 'สว่าง', 'ขึ้น': 'ลง', 'ลง': 'ขึ้น',
    'เข้า': 'ออก', 'ออก': 'เข้า', 'ยาว': 'สั้น', 'สั้น': 'ยาว', 'หนัก': 'เบา', 'เบา': 'หนัก',
    'รัก': 'เกลียด', 'เกลียด': 'รัก', 'สุข': 'ทุกข์', 'ทุกข์': 'สุข', 'มาก': 'น้อย', 'น้อย': 'มาก',
    'ดี': 'ไม่ดี', 'ร้าย': 'ดี', 'จริง': 'เท็จ', 'เท็จ': 'จริง', 'ได้': 'ไม่ได้', 'ขาว': 'ดำ', 'ดำ': 'ขาว'
  };
  const OP = { 'บวก': '+', '+': '+', 'ลบ': '-', '-': '-', 'คูณ': '*', '*': '*', 'x': '*', '×': '*',
    'หาร': '/', '/': '/', '÷': '/' };
  const MATH_RE = /^(-?\d+(?:\.\d+)?)(บวก|ลบ|คูณ|หาร|\+|-|\*|x|×|÷|\/)(-?\d+(?:\.\d+)?)(?:เท่ากับ|=)?(?:เท่าไร|เท่าไหร่|เท่าไหร|กี่|ได้เท่าไร|ได้เท่าไหร่)?[?？]?$/i;

  function fmtNum(x) {
    if (Number.isInteger(x)) return String(x);
    return String(Math.round(x * 1e6) / 1e6);
  }
  function fmtDate(d) {
    return THAI_DAYS[d.getDay()] + 'ที่ ' + d.getDate() + ' ' + THAI_MONTHS[d.getMonth()] + ' พ.ศ. ' + (d.getFullYear() + 543);
  }
  function shift(now, days) {
    const d = new Date(now.getTime());
    d.setDate(d.getDate() + days);
    return d;
  }
  function pick(list, seedText) {
    let h = 2166136261;
    for (let i = 0; i < seedText.length; i++) { h ^= seedText.charCodeAt(i); h = Math.imul(h, 16777619); }
    return list[(h >>> 0) % list.length];
  }

  function math(c) {
    const m = c.match(MATH_RE);
    if (!m) return null;
    const a = Number(m[1]), b = Number(m[3]), op = OP[m[2].toLowerCase()];
    if (!op) return null;
    if (op === '/' && b === 0) return { id: 'math', text: 'หารด้วยศูนย์ไม่ได้ค่ะ' };
    const r = op === '+' ? a + b : op === '-' ? a - b : op === '*' ? a * b : a / b;
    return { id: 'math', text: m[1] + ' ' + m[2] + ' ' + m[3] + ' เท่ากับ ' + fmtNum(r) + ' ค่ะ' };
  }

  const DAY_WORDS = [['มะรืนนี้', 2], ['มะรืน', 2], ['พรุ่งนี้', 1], ['เมื่อวานซืน', -2], ['เมื่อวาน', -1], ['วานนี้', -1], ['วันนี้', 0]];
  function day(c, now) {
    if (!/(วันอะไร|วันที่เท่าไร|วันที่เท่าไหร่|วันที่อะไร|วันไหน)[?？]?$/.test(c)) return null;
    for (const [w, n] of DAY_WORDS) {
      if (c.startsWith(w)) return { id: 'date', text: (n === 0 ? 'วันนี้' : w.replace('นี้', '') === 'วานนี' ? 'เมื่อวาน' : w) + 'เป็น' + fmtDate(shift(now, n)) + ' ค่ะ' };
    }
    return null;
  }

  function antonym(c) {
    if (c.indexOf('ตรงข้าม') < 0) return null;
    const keys = Object.keys(ANTONYMS).sort((a, b) => b.length - a.length);
    for (const k of keys) {
      if (c.indexOf(k) >= 0) return { id: 'antonym', text: 'ตรงข้ามกับ' + k + 'คือ' + ANTONYMS[k] + 'ค่ะ' };
    }
    return null;
  }

  function feelings(c) {
    if (ANXIOUS_RE.test(c) && c.length <= 40) return { id: 'feel', text: pick(ANXIOUS, c) };
    if (SAD_RE.test(c) && c.length <= 40) return { id: 'feel', text: pick(SAD, c) };
    return null;
  }

  function praise(c) {
    if (c.length > 30) return null;
    if (!/(มิ้ม|เธอ|คุณ)/.test(c)) return null;
    if (INSULT_RE.test(c)) return { id: 'insult', text: pick(INSULT, c) };
    if (PRAISE_RE.test(c)) return { id: 'praise', text: pick(PRAISE, c) };
    return null;
  }

  function nadia(c) {
    if (!/(นาเดียร์|นาดีย์|นาเดีย)/.test(c)) return null;
    if (!/(รู้จัก|คือ|เป็นใคร|อะไร|ไหม|มั้ย)/.test(c)) return null;
    return { id: 'nadia', text: 'พี่นาเดียร์เป็นโหมดคุยที่ใช้ API ที่คุณตั้งค่าไว้ในแอปค่ะ ส่วนมิ้มตอบจากความรู้ที่ฉันมีและที่คุณสอนไว้ค่ะ' };
  }

  function story(c) {
    if (!/(นิทาน)/.test(c) || c.length > 25) return null;
    return { id: 'story', text: pick(STORIES, c) };
  }

  const Skills = {
    match(input, now) {
      const raw = String(input || '');
      const compact = raw.replace(/\s+/g, '');
      if (!compact) return null;
      // เลขคณิตอ่านจากข้อความดิบ เพราะการ normalize ตัด * = × ออก
      const arith = math(compact);
      if (arith) return arith;
      const c = Text.normalize(raw).replace(/\s+/g, '');
      if (!c) return null;
      if (CRISIS_RE.test(c)) return { id: 'crisis', text: CRISIS };
      const when = now || new Date();
      return day(c, when) || nadia(c) || story(c) || antonym(c) || feelings(c) || praise(c) || null;
    },
    fmtDate: fmtDate
  };
  NINO.Skills = Skills;
})(typeof globalThis !== 'undefined' ? globalThis : this);
